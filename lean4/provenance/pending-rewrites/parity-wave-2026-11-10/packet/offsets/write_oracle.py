"""Copy frozen Offset functions for test-only family routing. No Lean translation or execution.
Run from the lane only to refresh ProbeOracle.sk; never used by production integration.
"""
from pathlib import Path
import hashlib
import json
import re

lane = Path(__file__).parent
root = lane.parents[2]
manifest = json.loads((lane/'manifest.json').read_text())
source = root/'sources/Modules/Lean/Meta/Offset/Part000.sk'
production = source.read_text()
# Brace-balanced function slicing, ignoring comments and strings.
def function(text, name):
    start = text.index('fun '+name+'(')
    brace = text.index('{', start)
    depth = 1
    pos = brace + 1
    quoted = False
    while depth:
        ch = text[pos]
        if quoted:
            if ch == '\\':
                pos += 2
                continue
            if ch == '"': quoted = False
        elif ch == '"': quoted = True
        elif text.startswith('//', pos):
            pos = text.index('\n', pos)
            continue
        elif ch == '{': depth += 1
        elif ch == '}': depth -= 1
        pos += 1
    return text[start:pos]

bodies = {}
for target in manifest['targets']:
    name = target['name'].split('.')[1]
    original = (lane/'originals'/(name+'.sk')).read_text()
    packetBody = original[original.index('// "'):original.index('\nmodule end;')].rstrip()
    assert hashlib.sha256(packetBody.encode()).hexdigest() == target['body_sha256']
    bodies[name] = function(original, name)
for name in ['f_Lean_Meta_getOffset_94d3d2e9f8', 'f_Meta_evalNat_evalPow_eeb69d1902',
             'f_Lean_Meta_mkOffset_02c44d4985', 'f_Lean_Meta_isNatZero_b7ef2f40e4']:
    bodies[name] = function(production, name)
renamed = {name: 'f_offsets_oracle_'+name.removeprefix('f_') for name in bodies}
output = ['// TEST ONLY. Frozen originals plus four verbatim local wrappers, identifiers rerouted.',
          '// Generated by write_oracle.py; never integrate these names into production.',
          '// General defeq/inference/testers/checkExponent remain shared, see REVIEW.md.']
for name, body in bodies.items():
    output.append('// Frozen body sha256: '+hashlib.sha256(body.encode()).hexdigest())
    for old, new in renamed.items():
        body = re.sub(r'\b'+re.escape(old)+r'\b', new, body)
    # The copied functions are global test helpers, so qualify the two remaining
    # unqualified production Offset calls. Qualified closure adapters stay verbatim.
    for helper in ['f_Lean_Meta_matchesInstance_d803c98e48', 'f_Meta_matchesInstance_spec_0_4b55788272']:
        body = re.sub(r'(?<![.\w])'+helper+r'\b', 'L4_Lean_Meta_Offset.'+helper, body)
    output.append(body)
(lane/'ProbeOracle.sk').write_text('\n\n'.join(output)+'\n')
