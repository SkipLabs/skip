#!/usr/bin/env python3
"""Generate a dependency-free family of distinct, ordinary `by decide` proofs.

Expected answers use prime valuations and are independently checked with
Python's factorial/gcd. No answers, proofs or computed factorial values are
exported to the Skip runtime by this tool.
"""
import argparse
import math
from pathlib import Path


def odd_primes(count):
    result = []
    n = 3
    while len(result) < count:
        if all(n % p for p in range(3, math.isqrt(n) + 1, 2)):
            result.append(n)
        n += 2
    return result


def valuation(n, prime):
    result = 0
    while n:
        n //= prime
        result += n
    return result


def source(bound, count):
    factorial = math.factorial(bound)
    output = [f'''-- Generated by tools/gcd_workload.py --bound {bound} --count {count}.
-- Distinct GCD claims sharing a factorial; no external libraries or axioms.
set_option exponentiation.threshold 200000
set_option maxRecDepth 200000
set_option maxHeartbeats 0
set_option Elab.async false

def fact : Nat → Nat
  | 0 => 1
  | n+1 => (n+1) * fact n

def bound : Nat := {bound}
def noise : Nat := 99
''']
    for prime in odd_primes(count):
        exponent = bound // (prime - 1) + bound // 20
        twos = min(exponent, valuation(bound, 2))
        others = min(exponent, valuation(bound, prime))
        expected = 2**twos * prime**others
        actual = math.gcd(factorial, (2 * prime)**exponent)
        if expected != actual:
            raise ValueError(f'independent GCD disagreement for prime {prime}')
        output.append(f'''
theorem factorial_gcd_{prime} :
    Nat.gcd (fact bound) ({2*prime} ^ {exponent}) = 2 ^ {twos} * {prime} ^ {others} := by
  decide

#print axioms factorial_gcd_{prime}
''')
    return '\n'.join(output)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--bound', type=int, default=20000)
    parser.add_argument('--count', type=int, default=16)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    if not 1 <= args.bound <= 100000 or not 1 <= args.count <= 100:
        parser.error('bound must be 1..100000 and count must be 1..100')
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(source(args.bound, args.count))


if __name__ == '__main__':
    main()
