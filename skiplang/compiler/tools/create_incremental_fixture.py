#!/usr/bin/env python3
"""Freeze the compiler workload and one common native runtime for both modes.

Only Git-tracked inputs are copied. Each benchmark mode gets its own target/cache
directory, while both use identical native runtime archives. The fixture retains
Skargo's normal development dispatcher, compiler tests, and package dependencies.
"""

import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import tarfile
import tempfile


def digest(path):
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, required=True)
    parser.add_argument("--revision", default="HEAD")
    parser.add_argument("--runtime-out", type=Path, required=True)
    parser.add_argument("--destination", type=Path, required=True)
    args = parser.parse_args()
    repo, out, runtime = (
        args.repo.resolve(),
        args.destination.resolve(),
        args.runtime_out.resolve(),
    )
    out.mkdir(parents=True, exist_ok=False)
    revision = subprocess.check_output(
        ["git", "rev-parse", args.revision], cwd=repo, text=True
    ).strip()
    packages = [
        "compiler",
        "prelude",
        "cli",
        "arparser",
        "sktest",
        "cc",
        "pkg-config",
    ]
    with tempfile.TemporaryFile(dir=out) as archive:
        subprocess.run(
            ["git", "archive", revision, *["skiplang/" + p for p in packages]],
            cwd=repo,
            stdout=archive,
            check=True,
        )
        archive.seek(0)
        with tarfile.open(fileobj=archive) as files:
            files.extractall(out, filter="data")
    native = out / "native"
    native.mkdir()
    archives = [
        runtime / "libskip_runtime.a",
        runtime / "libskip_runtime64.a",
        runtime / "libbacktrace/lib/libbacktrace.a",
    ]
    for path in archives:
        shutil.copy2(path, native / path.name)
    # Warm source-update comparisons must not accidentally use different runtime
    # magic/version objects generated by separate native dependency builds.
    build = ["fun main(): void {"]
    for path in sorted(native.iterdir()):
        for key in ["skc-link-lib", "rerun-if-changed"]:
            build.append(
                "  print_string("
                + json.dumps("skargo:" + key + "=" + str(path))
                + ");"
            )
    build += [
        '  print_string("skargo:skc-preamble=preamble/preamble64.ll");',
        '  print_string("skargo:rerun-if-changed=preamble/preamble64.ll")',
        "}",
        "",
    ]
    (out / "skiplang/prelude/build.sk").write_text("\n".join(build))
    subprocess.run(["git", "init", "-q"], cwd=out, check=True)
    subprocess.run(["git", "add", "skiplang"], cwd=out, check=True)
    subprocess.run(
        [
            "git",
            "-c",
            "user.name=Compiler benchmark",
            "-c",
            "user.email=compiler-benchmark@localhost",
            "commit",
            "-q",
            "-m",
            "Freeze compiler benchmark inputs from " + revision,
        ],
        cwd=out,
        check=True,
    )
    fixture_revision = subprocess.check_output(
        ["git", "rev-parse", "HEAD"], cwd=out, text=True
    ).strip()
    tracked = (
        subprocess.check_output(["git", "ls-files", "-z"], cwd=out)
        .decode()
        .split("\0")
    )
    metadata = {
        "source_revision": revision,
        "fixture_revision": fixture_revision,
        "packages": packages,
        "native_runtime": {
            str(p.relative_to(out)): digest(p) for p in sorted(native.iterdir())
        },
        "source_sha256": {
            p: digest(out / p) for p in tracked if p and (out / p).is_file()
        },
        "fixture_change": "Prelude build script packages the same frozen native archives in every mode.",
        "profile": "dev (normal merged compiler, formatter and test dispatcher)",
    }
    (out / "fixture.json").write_text(json.dumps(metadata, indent=2) + "\n")
    print(
        json.dumps(
            {
                "fixture": str(out),
                "revision": fixture_revision,
                "tracked_files": len(metadata["source_sha256"]),
            }
        )
    )


if __name__ == "__main__":
    main()
